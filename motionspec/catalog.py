def _rows(text):
    for line in text.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        yield [c.strip() for c in line.split("|")] + [""] * 3


def _build_cat2():
    out = {}
    for c1, text in _CAT2.items():
        out[c1] = {}
        for name, side, put, aka, *_ in _rows(text):
            assert name not in out[c1], (c1, name)
            out[c1][name] = dict(side=side or None, put=put or "정립", aka=[a.strip() for a in aka.split(",") if a.strip()])
    return out


def _build_named():
    out = {}
    for field, text in _NAMED.items():
        out[field] = {}
        for name, shape, side, parts, *_ in _rows(text):
            c1, _, c2 = (s.strip() for s in shape.partition(">"))
            detail = dict(p.split("=", 1) for p in (x.strip() for x in parts.split(";")) if p)
            assert name not in out[field], (field, name)
            base, _, phase = name.partition("(")
            phase = phase.rstrip(")") or None
            assert phase is None or phase in PHASES, (field, name)
            out[field][name] = dict(side=side or None, shape=(c1, c2), phase=phase, action=base.strip() if phase else None,
                                    parts={k.strip(): v.strip() for k, v in detail.items()})
    return out


CAT2 = _build_cat2()
NAMED = _build_named()
